using System.Collections.Generic;

namespace TiaMcpServer.ModelContextProtocol
{
    /// <summary>
    /// Shared response shapes for the project-mutating tools in McpServer (the [WriteTool] methods).
    ///
    /// Callers: every [WriteTool] tool in McpServer. Affected API: additive only - new DTOs, no
    /// existing response changed. Data: serialized into MCP structuredContent; all fields are
    /// nullable strings or string collections, no dates. No file I/O.
    ///
    /// Three shapes cover roughly thirty tools deliberately: minting one DTO per operation would
    /// triple the output schema surface for no gain to the caller.
    /// </summary>
    public class ResponseCreated : ResponseMessage
    {
        /// <summary>What was created, e.g. "Tag table", "Block group", "FB".</summary>
        public string? Kind { get; set; }
        public string? Name { get; set; }

        /// <summary>Root-relative path of the new object, where one applies.</summary>
        public string? Path { get; set; }
    }

    public class ResponseNetworkEdit : ResponseMessage
    {
        public string BlockPath { get; set; } = string.Empty;
        public string Action { get; set; } = string.Empty;
        public int NetworkIndex { get; set; }
        public int NetworksBefore { get; set; }
        public int NetworksAfter { get; set; }

        /// <summary>LAD/FBD parts of the new network moved into TIA's flow order.</summary>
        public int PartsReordered { get; set; }

        /// <summary>XML export of the block taken just before the import.</summary>
        public string? Backup { get; set; }

        public string? BackupWarning { get; set; }

        /// <summary>With 'previewFile': where the edited block XML was written (nothing imported).</summary>
        public string? PreviewFile { get; set; }
    }

    public class ResponseInterfaceEdit : ResponseMessage
    {
        public string BlockPath { get; set; } = string.Empty;
        public string Action { get; set; } = string.Empty;
        public string Section { get; set; } = string.Empty;
        public string MemberPath { get; set; } = string.Empty;

        /// <summary>The member before the change, e.g. 'bDone : Bool := false // Done flag'; null for add.</summary>
        public string? Before { get; set; }

        /// <summary>The member after the change; null for delete.</summary>
        public string? After { get; set; }

        public string? Backup { get; set; }
        public string? BackupWarning { get; set; }
        public string? PreviewFile { get; set; }
    }

    public class ResponseChangeLog : ResponseMessage
    {
        /// <summary>The day's log file (JSON lines).</summary>
        public string? File { get; set; }

        /// <summary>One entry per write tool call: time, tool, outcome, arguments, message, backup.</summary>
        public System.Collections.Generic.List<System.Text.Json.Nodes.JsonObject>? Entries { get; set; }
    }

    public class ResponseDeleted : ResponseMessage
    {
        public string? Kind { get; set; }
        public string? Path { get; set; }

        /// <summary>DeleteBlock/DeleteType: XML export of the object taken just before the delete.</summary>
        public string? Backup { get; set; }

        /// <summary>Why no backup was written, e.g. the object was inconsistent.</summary>
        public string? BackupWarning { get; set; }
    }

    public class ResponseRenamed : ResponseMessage
    {
        public string? Kind { get; set; }
        public string? OldPath { get; set; }
        public string? NewName { get; set; }
        public string? NewPath { get; set; }
    }

    public class ResponseImported : ResponseMessage
    {
        public string? Kind { get; set; }
        public string? GroupPath { get; set; }
        public string? ImportPath { get; set; }
    }

    public class ResponseGenerateBlocks : ResponseMessage
    {
        public IEnumerable<string>? GeneratedNames { get; set; }
        public int? Count { get; set; }
    }

    /// <summary>One block or PLC data type generated by ImportSources.</summary>
    public class ResponseImportedSourceItem
    {
        public string? Name { get; set; }

        /// <summary>Root-relative path of the new object in the project.</summary>
        public string? Path { get; set; }

        /// <summary>'block' or 'type'.</summary>
        public string? Kind { get; set; }
    }

    public class ResponseImportedSources : ResponseMessage
    {
        public string? Directory { get; set; }

        /// <summary>Objects generated per area: blocks, types.</summary>
        public IDictionary<string, int>? Written { get; set; }

        public IEnumerable<ResponseImportedSourceItem>? Items { get; set; }

        /// <summary>Files that could not be imported, with the reason.</summary>
        public IEnumerable<string>? Failures { get; set; }

        /// <summary>Backup files of the blocks and types the import replaced (named 'backup' so the change log finds them).</summary>
        public IEnumerable<string>? Backup { get; set; }

        public IEnumerable<string>? BackupWarnings { get; set; }
    }
}
